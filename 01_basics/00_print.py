# Print something to the console
print("Hello, World!")

# You can print multiple items by separating them with commas
print("The answer is", 42)

# You can also use string concatenation with the + operator
greeting = "Hello"
name = "Alice"
print(greeting + ", " + name + "!")

# F strings (f"string") allow us to embed variables directly in strings
print(f"{greeting}, {name}! Welcome to Python programming.")


