# ----------------------------
# 1) What is a comment?
# ----------------------------
# A comment is ignored by Python
# It is used to explain code for humans

print("Hello World")  # This comment is after code


# ----------------------------
# 2) Single-line comments
# ----------------------------
# Use # symbol

name = "Arun"  # storing name
age = 33       # storing age

print(name)
print(age)


# ----------------------------
# 3) Multi-line comments
# ----------------------------
# Python does not have real multi-line comments,
# but we use triple quotes for explanations

"""
This is a multi-line comment style.
It is often used for documentation.
Python ignores it if not assigned to a variable.
"""

print("Learning comments is easy 🙂")


# ----------------------------
# 4) Why comments are important
# ----------------------------
# Comments help:
# - Understand code later
# - Help teammates
# - Explain logic

