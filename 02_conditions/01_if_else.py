# If, Elif and Else Toghether
marks = 85
if marks >= 90: # if marks is greater than or equal to 90, then do the code below
    print("You got an A!")
elif marks >= 80: # if the above condition is false and marks is greater than or equal to 80, then do the code below
    print("You got a B!")
elif marks >= 70: # if the above conditions are false and marks is greater than or equal to 70, then do the code below
    print("You got a C!")
else: # if all the above conditions are false, then do the code below
    print("You got a D!")

