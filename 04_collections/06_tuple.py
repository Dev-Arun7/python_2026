"""
--------------------------------------------------
TUPLES — BASICS
--------------------------------------------------

Tuple = ()

Properties:
- Ordered
- Immutable
- Allows duplicates
"""

# --------------------------------------------------
# Creating a Tuple
# --------------------------------------------------

fruits = ("apple", "orange", "grape", "banana")

print("\nOriginal tuple:")
print(fruits)


# --------------------------------------------------
# Indexing
# --------------------------------------------------

print("\nFirst item:", fruits[0])
print("Last item:", fruits[-1])


# --------------------------------------------------
# Slicing
# --------------------------------------------------

print("\nFirst two items:", fruits[0:2])


# --------------------------------------------------
# Length
# --------------------------------------------------

print("\nLength:", len(fruits))


# --------------------------------------------------
# Duplicate Values
# --------------------------------------------------

numbers = (1, 2, 2, 3)

print("\nDuplicates allowed:")
print(numbers)


# --------------------------------------------------
# Single Item Tuple
# --------------------------------------------------

single = ("apple",)

print("\nSingle item tuple:")
print(single)


# --------------------------------------------------
# Loop Through Tuple
# --------------------------------------------------

print("\nLooping fruits:")

for item in fruits:
    print(item)


# --------------------------------------------------
# Membership Check
# --------------------------------------------------

print("\nIs apple in fruits?", "apple" in fruits)


# --------------------------------------------------
# Cannot Modify Tuple
# --------------------------------------------------

# fruits[0] = "mango"  ❌ Error


# --------------------------------------------------
# Empty Tuple
# --------------------------------------------------

empty_tuple = ()

print("\nEmpty tuple:")
print(empty_tuple)